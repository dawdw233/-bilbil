class LoginFailed(Exception):
    """扫码成功了，但 B站 没把 cookie 交出来（多半是被风控了）。"""


_QR_GENERATE = "https://passport.bilibili.com/x/passport-login/web/qrcode/generate"
_QR_POLL = "https://passport.bilibili.com/x/passport-login/web/qrcode/poll"


def _query_to_dict(query: str) -> dict:
    out = {}
    for part in (query or "").split("&"):
        if "=" in part:
            k, v = part.split("=", 1)
            out[k] = unquote(v)
    return out


class QrWebLogin:
    """自己走一遍 B站 网页扫码登录，不依赖 bilibili-api 的 QrCodeLogin。

    踩到的坑（2026-11-01）：B站 改了扫码成功后的返回。以前 url 里直接带
        SESSDATA=...&bili_jct=...&DedeUserID=...
    现在只给
        https://passport.biligame.com/x/passport-login/web/crossDomain?ticket=...&gourl=...
    cookie 得拿这个 ticket 再请求一次 crossDomain，靠 Set-Cookie 下发；而且这一步
    要和轮询用**同一个会话**（buvid3 之类是绑一起的），所以整条链路共用一个
    curl_cffi Session。bilibili-api 17.4.1 只解析 url 的 query，因此永远是空 sessdata
    —— 表现就是「扫了码、日志说成功，插件还是未登录」。
    """

    def __init__(self) -> None:
        from curl_cffi import requests as creq

        self._creq = creq
        self._session = creq.Session(impersonate="chrome")
        self._key = ""
        self._link = ""
        self._picture = None
        self._terminal = ""
        self._cred = None
        self._diag = ""

    def has_done(self) -> bool:
        return self._cred is not None

    @property
    def qr_link(self) -> str:
        """扫码原始链接（= 二维码内容）。"""
        return self._link

    def get_credential(self):
        return self._cred

    def get_qrcode_picture(self):
        return self._picture

    def get_qrcode_terminal(self) -> str:
        return self._terminal

    async def generate_qrcode(self) -> None:
        await asyncio.to_thread(self._generate)

    async def check_state(self):
        return await asyncio.to_thread(self._poll)

    def _generate(self) -> None:
        resp = self._session.get(_QR_GENERATE, timeout=20)
        data = (resp.json() or {}).get("data") or {}
        self._link = str(data.get("url") or "")
        self._key = str(data.get("qrcode_key") or "")
        if not self._link or not self._key:
            raise RuntimeError("B站 没生成二维码（generate 接口返回空）")
        qr = qrcode.QRCode(box_size=8, border=2)
        qr.add_data(self._link)
        qr.make(fit=True)
        buf = io.BytesIO()
        qr.make_image().save(buf, format="PNG")
        self._picture = Picture.from_content(buf.getvalue(), "png")
        self._terminal = qrcode_terminal.qr_terminal_str(self._link)

    def _poll(self):
        resp = self._session.get(
            _QR_POLL, params={"qrcode_key": self._key}, timeout=20
        )
        data = (resp.json() or {}).get("data") or {}
        code = data.get("code")
        if code == 86101:
            return QrCodeLoginEvents.SCAN
        if code == 86090:
            return QrCodeLoginEvents.CONF
        if code == 86038:
            return QrCodeLoginEvents.TIMEOUT

        cookies = self._exchange_cookies(str(data.get("url") or ""))
        sessdata = str(cookies.get("SESSDATA") or "")
        if not sessdata:
            raise LoginFailed(
                f"B站 回了登录成功但没下发 cookie（{self._diag or '没拿到 ticket'}）"
            )
        self._cred = Credential(
            sessdata=sessdata,
            bili_jct=str(cookies.get("bili_jct") or ""),
            buvid3=str(cookies.get("buvid3") or "") or None,
            dedeuserid=str(cookies.get("DedeUserID") or ""),
            ac_time_value=str(data.get("refresh_token") or ""),
        )
        return QrCodeLoginEvents.DONE

    def _exchange_cookies(self, url: str) -> dict:
        """老接口直接从 query 里抠；新接口拿 ticket 请求 crossDomain 换 cookie。"""
        got: dict = {}
        if url and "?" in url:
            got.update(_query_to_dict(url.split("?", 1)[1]))
        if got.get("SESSDATA") or not url:
            self._diag = "url 里没有 cookie"
            return got

        try:
            resp = self._session.get(
                url,
                timeout=20,
                allow_redirects=True,
                headers={"Referer": "https://www.bilibili.com/"},
            )
            set_cookie = ", ".join(
                sorted({h.split("=", 1)[0] for h in resp.headers.get_list("set-cookie")})
            )
            jar = sorted({c.name for c in self._session.cookies.jar if c.name})
            self._diag = (
                f"crossDomain HTTP {resp.status_code}；Set-Cookie: {set_cookie or '无'}；"
                f"会话 cookie: {', '.join(jar) or '无'}"
            )
            print(f"[bili-login] {self._diag}", file=sys.stderr)
        except Exception as exc:
            self._diag = f"crossDomain 请求失败 {type(exc).__name__}: {exc}"
            print(f"[bili-login] {self._diag}", file=sys.stderr)
            return got

        for cookie in self._session.cookies.jar:
            if cookie.name and not got.get(cookie.name):
                got[cookie.name] = cookie.value
        return got



def get_cred() -> Credential:
    """获取凭证，未登录时引导用户调用 bili_login"""
    cred = load_credential()
    if not cred:
        raise Exception("未登录B站！请先调用 bili_login 工具获取登录二维码，让用户扫码登录。")
    return cred


# ========== Tool: 扫码登录（生成二维码） ==========

@tool()
async def bili_login() -> str:
    """
    生成B站登录二维码，返回二维码图片（base64）供用户扫码。
    用户扫码后，调用 bili_login_check 检查登录状态。

    Returns:
        包含二维码base64图片数据的JSON，前端可直接渲染为图片展示给用户
    """
    global _login_session

    # 如果已有凭证，直接返回
    cred = load_credential()
    if cred:
        return json.dumps({
            "status": "already_logged_in",
            "message": "已登录B站，无需重复登录",
        }, ensure_ascii=False)

    # 生成新的登录会话
    _login_session = QrWebLogin()
    await _login_session.generate_qrcode()

    # 获取二维码图片的 base64（无损PNG）
    pic = _login_session.get_qrcode_picture()
    img_base64 = base64.b64encode(pic.content).decode("utf-8")

    # 保存二维码图片到项目根目录
    qr_file = Path(__file__).parent / "qrcode_login.png"
    with open(qr_file, "wb") as f:
        f.write(pic.content)

    # 获取终端文本版二维码（纯文本客户端备用）
    terminal_qr = _login_session.get_qrcode_terminal()

    # 获取原始扫码URL（用户也可以手动在B站App打开）
    qr_url = getattr(_login_session, "qr_link", "") or getattr(
        _login_session, "_QrCodeLogin__qr_link", ""
    )

    return json.dumps({
        "status": "qrcode_ready",
        "message": "请用B站App扫描二维码登录（180秒内有效）",
        "qrcode_image": f"data:image/png;base64,{img_base64}",
        "qrcode_file": str(qr_file),
        "qrcode_terminal": terminal_qr,
        "qrcode_url": qr_url,
        "next_step": "用户扫码后，请调用 bili_login_check 检查登录状态",
    }, ensure_ascii=False)


# ========== Tool: 检查登录状态 ==========

@tool()
async def bili_login_check() -> str:
    """
    检查B站扫码登录状态。在用户扫码后调用此工具。
    如果返回 "scanning" 或 "confirming"，请等待几秒后再次调用。
    如果返回 "done"，登录成功，可以使用其他工具了。
    如果返回 "timeout"，需要重新调用 bili_login 生成新二维码。

    Returns:
        当前登录状态
    """
    global _login_session

    if not _login_session:
        # 没有登录会话，检查是否已登录
        cred = load_credential()
        if cred:
            return json.dumps({
                "status": "already_logged_in",
                "message": "已登录B站",
            }, ensure_ascii=False)
        return json.dumps({
            "status": "no_session",
            "message": "没有进行中的登录，请先调用 bili_login 生成二维码",
        }, ensure_ascii=False)

    try:
        state = await _login_session.check_state()
    except LoginFailed as exc:
        _login_session = None
        qr_file = Path(__file__).parent / "qrcode_login.png"
        if qr_file.exists():
            try:
                qr_file.unlink()
            except OSError:
                pass
        return json.dumps({
            "status": "failed",
            "message": str(exc),
        }, ensure_ascii=False)

    if state == QrCodeLoginEvents.SCAN:
        return json.dumps({
            "status": "scanning",
            "message": "还没扫码（二维码 180 秒内有效），请用 B站 App 扫码",
            "next_step": "用户扫码后，请等待3秒再次调用 bili_login_check",
        }, ensure_ascii=False)

    elif state == QrCodeLoginEvents.CONF:
        return json.dumps({
            "status": "confirming",
            "message": "用户已确认，正在处理...",
            "next_step": "请等待2秒后再次调用 bili_login_check",
        }, ensure_ascii=False)

    elif state == QrCodeLoginEvents.TIMEOUT:
        _login_session = None
        # 清理二维码文件
        qr_file = Path(__file__).parent / "qrcode_login.png"
        if qr_file.exists():
            qr_file.unlink()
        return json.dumps({
            "status": "timeout",
            "message": "二维码已过期，请重新调用 bili_login 生成新二维码",
        }, ensure_ascii=False)

    elif state == QrCodeLoginEvents.DONE:
        # 登录成功，保存凭证
        cred = _login_session.get_credential()
        if not str(cred.sessdata or "").strip():
            # ⚠️ 空凭证绝不能落盘：写了它，之后每个工具都会「有文件但没登录」，
            #    页面还显示成功，排查起来像见鬼（2026-11-01 真踩到了）。
            _login_session = None
            return json.dumps({
                "status": "failed",
                "message": "B站 回了成功但凭证是空的（cookie 没拿到），再扫一次或换个时间",
            }, ensure_ascii=False)
        # ⚠️ 原子写：原来直接 open(w) 先截断再 dump，写到一半被打断就毁掉旧凭证，
        #    此后所有工具都读不了。（2026-10-16 审查修）
        tmp_cred = CRED_FILE.with_name(CRED_FILE.name + ".tmp")
        with open(tmp_cred, "w", encoding="utf-8") as f:
            json.dump({
                "sessdata": cred.sessdata,
                "bili_jct": cred.bili_jct,
                "buvid3": cred.buvid3,
                "dedeuserid": cred.dedeuserid,
            }, f)
        os.replace(tmp_cred, CRED_FILE)
        _login_session = None
        # 清理二维码文件
        qr_file = Path(__file__).parent / "qrcode_login.png"
        if qr_file.exists():
            qr_file.unlink()
        return json.dumps({
            "status": "done",
            "message": "登录成功！凭证已保存，现在可以使用所有B站功能了",
        }, ensure_ascii=False)

    return json.dumps({
        "status": "unknown",
        "message": f"未知状态: {state}",
    }, ensure_ascii=False)


# ========== 凭证是否**真的**还有效 ==========

_NAV_URL = "https://api.bilibili.com/x/web-interface/nav"


def _cred_alive_sync(cred: Credential) -> tuple[bool, str]:
    """只有问 nav 接口才能真判断 cookie 还有没有效。

    ⚠️ 别拿 user.User(uid).get_user_info() 当校验：那是公开接口，拿一条瞎编的
    SESSDATA 它照样回「凭证有效」（2026-11-01 实测踩到，等于没有校验）。
    nav 接口未登录时 data.isLogin=false，才是权威信号。
    """
    cookies = {"SESSDATA": str(getattr(cred, "sessdata", "") or "")}
    if getattr(cred, "bili_jct", ""):
        cookies["bili_jct"] = str(cred.bili_jct)
    if getattr(cred, "dedeuserid", ""):
        cookies["DedeUserID"] = str(cred.dedeuserid)
    try:
        from curl_cffi import requests as creq

        resp = creq.get(_NAV_URL, cookies=cookies, impersonate="chrome", timeout=15)
        body = resp.json() or {}
        data = body.get("data") or {}
    except Exception as exc:
        # 网络抖一下不能当"掉登录"，否则会误把人踢去重扫
        return True, f"验证请求失败（{type(exc).__name__}），先按已登录处理"

    code = body.get("code")
    if code == -101:
        # nav 对"cookie 无效/过期"回的就是 -101（账号未登录）
        return False, "凭证已过期或被踢下线，需要重新扫码登录"
    if code != 0:
        # -352 / -412 是风控或限流，不是"你没登录"。这时候宁可放过，
        # 不然会把好的登录状态误判成过期，把人拦在门外。
        return True, f"nav 返回 {code}（{body.get('message') or '可能被限流'}），先按已登录处理"

    if data.get("isLogin") and str(data.get("mid") or ""):
        return True, f"凭证有效（uid {data.get('mid')}）"
    return False, "凭证已过期或被踢下线，需要重新扫码登录"


async def bili_cred_alive() -> tuple[bool, str]:
    """(是否仍然登录, 说明)。没有凭证文件时直接 False。"""
    cred = load_credential()
    if not cred or not str(getattr(cred, "sessdata", "") or "").strip():
        return False, "还没登录 B站"
    return await asyncio.to_thread(_cred_alive_sync, cred)


